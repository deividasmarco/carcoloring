// Writes src/ui/fontMetrics.generated.ts: advance widths (in em) of the
// characters vehicle names use, read from the bundled Michroma font, so names
// can be sized to fit exactly on every platform.
//   node scripts/font-metrics.mjs
import { readFileSync, writeFileSync } from 'fs';

const FONT = 'node_modules/@expo-google-fonts/michroma/400Regular/Michroma_400Regular.ttf';
const CHARS = ' ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-&\'.';

const buf = readFileSync(FONT);
const u16 = (o) => buf.readUInt16BE(o);
const u32 = (o) => buf.readUInt32BE(o);
const tables = {};
for (let i = 0, n = u16(4); i < n; i++) {
  const rec = 12 + i * 16;
  tables[buf.toString('ascii', rec, rec + 4)] = u32(rec + 8);
}
const unitsPerEm = u16(tables.head + 18);
const numberOfHMetrics = u16(tables.hhea + 34);
const advanceOf = (glyph) => u16(tables.hmtx + 4 * Math.min(glyph, numberOfHMetrics - 1));

// cmap: the Unicode BMP subtable (format 4).
let sub = -1;
for (let i = 0, n = u16(tables.cmap + 2); i < n; i++) {
  const rec = tables.cmap + 4 + i * 8;
  const platform = u16(rec);
  const encoding = u16(rec + 2);
  const offset = tables.cmap + u32(rec + 4);
  if (u16(offset) === 4 && (platform === 3 || platform === 0) && (encoding === 1 || platform === 0)) sub = offset;
}
if (sub < 0) throw new Error('no format-4 cmap');
const segX2 = u16(sub + 6);
const ends = sub + 14;
const starts = ends + segX2 + 2;
const deltas = starts + segX2;
const rangeOffsets = deltas + segX2;
function glyphOf(code) {
  for (let s = 0; s < segX2 / 2; s++) {
    if (u16(ends + s * 2) < code) continue;
    const start = u16(starts + s * 2);
    if (start > code) return 0;
    const delta = buf.readInt16BE(deltas + s * 2);
    const ro = u16(rangeOffsets + s * 2);
    if (ro === 0) return (code + delta) & 0xffff;
    const g = u16(rangeOffsets + s * 2 + ro + (code - start) * 2);
    return g === 0 ? 0 : (g + delta) & 0xffff;
  }
  return 0;
}

const widths = {};
for (const ch of CHARS) {
  const g = glyphOf(ch.codePointAt(0));
  if (!g) throw new Error(`Michroma has no glyph for ${JSON.stringify(ch)}`);
  widths[ch] = Math.round((advanceOf(g) / unitsPerEm) * 10000) / 10000;
}
const widest = Math.max(...Object.values(widths));
writeFileSync(
  'src/ui/fontMetrics.generated.ts',
  `// Generated by scripts/font-metrics.mjs from ${FONT}. Do not edit.
/** Michroma advance widths in em, for the characters vehicle names use (upper case). */
export const MICHROMA_ADVANCE: Readonly<Record<string, number>> = ${JSON.stringify(widths, null, 2)};

/** The widest of them, used for any other character. */
export const MICHROMA_WIDEST = ${widest};
`,
);
console.log(`unitsPerEm ${unitsPerEm}; ${Object.keys(widths).length} widths; A=${widths.A} M=${widths.M} I=${widths.I} space=${widths[' ']}`);
